/**
 * Целевая оценка диаметра каната: модель без груза, algorithmVersion 4.0.0.
 *
 * x — dTex покупной исходной нити, n — число нитей в одной пряди (прядей
 * всегда три), D — миллиметры. u = ln(x / 300), v = ln(n), натуральный
 * логарифм. Модель лог-квадратична по x и лог-линейна по n; груз, бренд и
 * источник в неё не входят.
 *
 * Коэффициенты записаны всеми знаками и не округляются: результат должен
 * совпадать с приёмочной таблицей с абсолютной точностью 1e-9. Промежуточного
 * округления нет — точность обрезается только при выводе.
 *
 * Модель подобрана по data/rope-calibration (очищенная выборка 130 строк,
 * обучение 128, цель — сумма квадратов относительных ошибок, вес 1). Подбор
 * и LOFO воспроизводятся скриптом data/rope-calibration/calibrate_no_load.py.
 *
 * Версия 3.0.0 учитывала груз и удалена; 2.0.0 — степенная формула
 * 0.0204055952 × dtex^0.5293147610 × n^0.5366123919 в замороженном контракте v1.
 */
export function calculateDiameterMm(dtex: number, threadsPerStrand: number): number {
  const u = Math.log(dtex / 300);
  const v = Math.log(threadsPerStrand);

  return Math.exp(
    -0.8841755979848913 +
      0.6318544934210768 * u +
      0.5435747556354212 * v -
      0.061470048768181726 * u * u,
  );
}
