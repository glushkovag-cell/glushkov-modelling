/**
 * Оценка диаметра каната.
 *
 * Выражение совпадает с RopeCalc.html до операции: сначала
 * 0.0204055952 × dtex^0.5293147610, затем умножение на n^0.5366123919.
 * Порядок умножения сохранён, чтобы результат совпадал с эталоном бит в бит.
 *
 * Алгоритм 2.0.0: коэффициенты перекалиброваны по расширенной выборке,
 * диапазон n расширен до 1–5. Версия 1.0.0 использовала
 * 0.01752 × dtex^0.5437 × n^0.5880 при n = 1–3.
 *
 * Промежуточного округления нет: точность обрезается только при выводе.
 */
export function calculateDiameterMm(dtex: number, threadsPerStrand: number): number {
  return 0.0204055952 * Math.pow(dtex, 0.5293147610) * Math.pow(threadsPerStrand, 0.5366123919);
}
